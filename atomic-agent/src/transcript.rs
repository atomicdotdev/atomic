// CRDT Anchor Helpers

/// Extract the (change_id, leaf_idx) tuple from a LeafOp, if it references an existing leaf.
///
/// Insert ops don't carry an assigned LeafId (the ID is assigned during apply),
/// so they return None. Delete, Replace, and Restore reference existing leaves.
fn leaf_op_id(op: &atomic_core::crdt::LeafOp) -> Option<(u64, u32)> {
    op.leaf_id()
        .map(|lid| (lid.change_id().get(), lid.leaf_idx()))
}

